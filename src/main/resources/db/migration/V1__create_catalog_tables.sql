-- Catalog: items and their sellable variants.
-- A variant is the stock-keeping unit (SKU): it is what gets priced, stocked and sold.

CREATE TABLE items
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(150)             NOT NULL,
    description VARCHAR(1000),
    base_price  DECIMAL(12, 2)           NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_items_base_price CHECK (base_price >= 0)
);

CREATE INDEX ix_items_name ON items (name);

CREATE TABLE variants
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id        BIGINT                   NOT NULL,
    sku            VARCHAR(64)              NOT NULL,
    name           VARCHAR(150)             NOT NULL,
    -- NULL means "inherit the item's base price"
    price          DECIMAL(12, 2),
    stock_quantity INT                      NOT NULL DEFAULT 0,
    version        BIGINT                   NOT NULL DEFAULT 0,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_variants_sku UNIQUE (sku),
    CONSTRAINT fk_variants_item FOREIGN KEY (item_id) REFERENCES items (id) ON DELETE CASCADE,
    CONSTRAINT ck_variants_price CHECK (price IS NULL OR price >= 0),
    -- Last line of defence against overselling: the database itself refuses negative stock.
    CONSTRAINT ck_variants_stock CHECK (stock_quantity >= 0)
);

CREATE INDEX ix_variants_item_id ON variants (item_id);

CREATE TABLE variant_attributes
(
    variant_id BIGINT       NOT NULL,
    attr_name  VARCHAR(50)  NOT NULL,
    attr_value VARCHAR(100) NOT NULL,
    CONSTRAINT pk_variant_attributes PRIMARY KEY (variant_id, attr_name),
    CONSTRAINT fk_variant_attributes_variant FOREIGN KEY (variant_id) REFERENCES variants (id) ON DELETE CASCADE
);
