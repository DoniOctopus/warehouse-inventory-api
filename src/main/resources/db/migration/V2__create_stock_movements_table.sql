-- Append-only ledger of every stock change, so current stock levels can always be explained.

CREATE TABLE stock_movements
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    variant_id      BIGINT                   NOT NULL,
    type            VARCHAR(20)              NOT NULL,
    -- signed: positive adds stock, negative removes it
    quantity_change INT                      NOT NULL,
    -- stock level right after this movement was applied
    quantity_after  INT                      NOT NULL,
    reason          VARCHAR(255),
    -- external reference such as an order number
    reference       VARCHAR(64),
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_stock_movements_variant FOREIGN KEY (variant_id) REFERENCES variants (id) ON DELETE CASCADE,
    CONSTRAINT ck_stock_movements_change CHECK (quantity_change <> 0),
    CONSTRAINT ck_stock_movements_after CHECK (quantity_after >= 0)
);

CREATE INDEX ix_stock_movements_variant_created ON stock_movements (variant_id, created_at);
