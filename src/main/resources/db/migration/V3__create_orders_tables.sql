-- Sales orders. Placing an order deducts stock; cancelling it puts the stock back.

CREATE TABLE orders
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number VARCHAR(32)              NOT NULL,
    status       VARCHAR(20)              NOT NULL,
    total_amount DECIMAL(14, 2)           NOT NULL,
    note         VARCHAR(500),
    cancelled_at TIMESTAMP WITH TIME ZONE,
    version      BIGINT                   NOT NULL DEFAULT 0,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_orders_order_number UNIQUE (order_number),
    CONSTRAINT ck_orders_total CHECK (total_amount >= 0)
);

CREATE INDEX ix_orders_status_created ON orders (status, created_at);

-- Order lines snapshot the SKU, names and price at the time of sale, so an order
-- stays accurate even if the variant is later repriced, renamed or deleted.
-- variant_id is therefore deliberately not a foreign key.
CREATE TABLE order_lines
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id     BIGINT         NOT NULL,
    variant_id   BIGINT         NOT NULL,
    sku          VARCHAR(64)    NOT NULL,
    item_name    VARCHAR(150)   NOT NULL,
    variant_name VARCHAR(150)   NOT NULL,
    unit_price   DECIMAL(12, 2) NOT NULL,
    quantity     INT            NOT NULL,
    line_total   DECIMAL(14, 2) NOT NULL,
    CONSTRAINT fk_order_lines_order FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE CASCADE,
    CONSTRAINT ck_order_lines_quantity CHECK (quantity > 0)
);

CREATE INDEX ix_order_lines_order_id ON order_lines (order_id);
